# Each entry's findings_by_category is still the MAXIMUM allowed count for that category in
# that file -- check-terminology-guardrail.mjs fails CI only when a re-scan finds MORE than
# this recorded baseline (new, never-before-seen debt), never on the pre-existing count
# itself. Category-level disposition reasoning (see this generator script's own module
# docstring for the full investigation each rule reflects):
#   - hardcoded_iso_date: bare-ISO-date-shape regex false positive (changelog/gap-closure/
#     task-ID/commit-date references in filenames, IDs, and prose -- this repo names files and
#     task/instruction IDs with an embedded date as standard practice), not human example data.
#   - src/db/seed.ts + *.test.ts(x): Phase 2's own out-of-scope classification (local-dev/test
#     fixtures, not AI prompt/template authoring).
