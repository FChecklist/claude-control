HARDCODED_DATE_REASON = (
    "Phase 5 full-repo baseline (2026-07-24): permanent exemption -- bare-ISO-date-shape regex "
    "false positive. This repo names files, task IDs, and instruction IDs with an embedded date "
    "as standard practice (changelog/gap-closure/task-ID/commit-date references), which is what "
    "every non-comment/non-code instance in this category resolves to on direct read -- not human "
    "example/sample data. {count} finding(s) in this file, permanent, not migrated."
)

SEED_FIXTURE_REASON = (
    "Phase 5 full-repo baseline (2026-07-24): permanent exemption per Phase 2's own directory "
    "classification (task-20260724-115921-phase2-directory-scoped-guardrail-rollout, unchanged) -- "
    "src/db/seed.ts + *.test.ts(x) local-dev/test fixture example data is explicitly out of scope "
    "for placeholder migration. {count} finding(s) in this file, permanent, not migrated."
)

PROSE_EXAMPLE_REASON = (
    "Phase 5 full-repo baseline (2026-07-24): permanent exemption -- genuine illustrative prose/"
    "example content in a non-code governance/design/taxonomy document (Phase 5's own file-type-"
    "scope expansion past .ts/.tsx surfaces this for the first time). <Entity.Attribute> "
    "placeholder syntax is for AI prompt/template substitution; forcing it into narrative prose "
    "would make the prose read as broken template text to a human reader rather than real "
    "illustrative content -- same reasoning Phase 4 already applied to "
    "src/lib/orchestra-mock-data.ts's static preview data (confirmed out of this guardrail's "
    "actual prompt/template scope on direct read). {count} finding(s) in this file, permanent, "
    "not migrated."
)

CODE_LITERAL_REASON = (
    "Phase 5 full-repo baseline (2026-07-24): permanent exemption -- confirmed on direct read to "
    "be non-migratable (format-shape description string, protocol/version literal, or a literal "
    "otherwise outside this guardrail's actual prompt/template scope), same disposition class as "
    "Phase 4's existing per-file findings in this category. {count} finding(s) in this file, "
    "permanent, not migrated."
)

CODE_EXTS = (".ts", ".tsx")


def is_seed_or_test(rel_path):
    return rel_path == "src/db/seed.ts" or rel_path.endswith(".test.ts") or rel_path.endswith(".test.tsx")


def build_reason(rel_path, category, count):
    if category == "hardcoded_iso_date":
        return HARDCODED_DATE_REASON.format(count=count)
    if is_seed_or_test(rel_path):
        return SEED_FIXTURE_REASON.format(count=count)
    is_code = rel_path.endswith(CODE_EXTS)
    if is_code:
        return CODE_LITERAL_REASON.format(count=count)
    return PROSE_EXAMPLE_REASON.format(count=count)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--scan-report", required=True, help="TERMINOLOGY_GUARDRAIL_2026-07-24.py JSON report")
    parser.add_argument("--repo-root", required=True, help="compliance-tracker checkout root the report's source paths are relative/absolute to")
    parser.add_argument("--output", required=True, help="path to write the regenerated exemptions.yaml")
    args = parser.parse_args()

    with open(args.scan_report) as f:
        report = json.load(f)

    counts = {}
    for finding in report["findings"]:
        source = finding["source"]
        rel = os.path.relpath(source, args.repo_root) if os.path.isabs(source) else source
        key = (rel, finding["category"])
        counts[key] = counts.get(key, 0) + 1

    by_file = {}
    for (rel_path, category), count in counts.items():
        by_file.setdefault(rel_path, []).append((category, count))

    lines = []
    for rel_path in sorted(by_file):
        cats = sorted(by_file[rel_path])
        reasons = []
        for category, count in cats:
            reasons.append(build_reason(rel_path, category, count))
        # one reason string per file, de-duplicated (a file usually has one dominant
        # category-class reason; join distinct ones only if truly mixed)
        reason_text = " ".join(dict.fromkeys(reasons))
        lines.append(f"  - file: {rel_path}")
        lines.append(f"    reason: \"{reason_text}\"")
        lines.append("    findings_by_category:")
        for category, count in cats:
            lines.append(f"      {category}: {count}")

    header = HEADER.format(
        files_scanned=report["meta"]["files_scanned_count"],
        total_findings=report["summary"]["total_findings"],
    )
    body = "\n".join(lines) + "\n"

    with open(args.output, "w") as f:
        f.write(header + body)

    print(f"Wrote {args.output}")
    print(f"  files_with_findings={len(by_file)} total_findings={sum(c for _, c in counts.items()) if False else report['summary']['total_findings']}")


if __name__ == "__main__":
    main()
